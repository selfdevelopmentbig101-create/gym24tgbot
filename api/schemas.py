"""Request and response shapes (validated by pydantic, shown in /api/docs)."""
from datetime import date
from typing import Literal

from pydantic import BaseModel, Field

from database.enums import Diet, Equipment, Experience, Goal, Injury, Sex

LanguageCode = Literal["en", "ru", "uz"]


class LanguageOption(BaseModel):
    code: LanguageCode
    name: str


class MeOut(BaseModel):
    first_name: str = Field(description="From Telegram's verified initData; not stored")
    language: LanguageCode | None = Field(description="The user's saved choice; null = not chosen yet")
    language_effective: LanguageCode = Field(description="Language to show now")
    disclaimer_accepted: bool
    profile_complete: bool = Field(description="False = show onboarding")


class LanguageIn(BaseModel):
    language: LanguageCode


class ConfigOut(BaseModel):
    app_name: str
    attribution: str = Field(description="Credits for the exercise images (Profile > Credits)")
    languages: list[LanguageOption]
    profile_rules: "ProfileRules"


class HealthOut(BaseModel):
    status: Literal["ok"]


# ---------- Stage 2: profile and targets ----------

class ProfileRules(BaseModel):
    """Allowed answers, so the Mini App validates with the same limits as the server."""
    age: tuple[int, int]
    height_cm: tuple[float, float]
    weight_kg: tuple[float, float]
    training_days: tuple[int, int]
    goals: list[Goal]
    sexes: list[Sex]
    experience: list[Experience]
    equipment: list[Equipment]
    injuries: list[Injury]
    diets: list[Diet]


class ProfileIn(BaseModel):
    """All onboarding answers (PUT /api/profile). Ranges are checked by services/validation.py."""
    goal: Goal
    age: int
    sex: Sex
    height_cm: float
    weight_kg: float
    experience: Experience
    training_days: int
    equipment: Equipment
    injuries: list[Injury] = Field(default_factory=list, max_length=len(Injury))
    diet: Diet
    target_weight_kg: float | None = Field(default=None, description="Optional goal weight")


class ProfilePatch(BaseModel):
    """Change some answers (PATCH /api/profile). Send only the fields that change."""
    goal: Goal | None = None
    age: int | None = None
    sex: Sex | None = None
    height_cm: float | None = None
    weight_kg: float | None = None
    experience: Experience | None = None
    training_days: int | None = None
    equipment: Equipment | None = None
    injuries: list[Injury] | None = Field(default=None, max_length=len(Injury))
    diet: Diet | None = None
    target_weight_kg: float | None = Field(default=None, description="null clears it")


class GoalOut(BaseModel):
    target_weight_kg: float
    to_gain_kg: float
    estimated_date: date
    earliest_date: date
    latest_date: date


class TargetsOut(BaseModel):
    calories: int
    protein_g: int
    carbs_g: int
    fat_g: int
    bmr: int
    tdee: int
    surplus: int = Field(description="Calories above maintenance (0 for recomposition)")
    protein_g_per_kg: float
    weekly_gain_kg: tuple[float, float]
    goal: GoalOut | None = Field(description="null: no goal weight, already reached, or recomposition")
    notes: list[str] = Field(description="Advice keys, e.g. note_under_18")


class ProfileOut(BaseModel):
    goal: Goal
    age: int
    sex: Sex
    height_cm: float
    weight_kg: float
    experience: Experience
    training_days: int
    equipment: Equipment
    injuries: list[Injury]
    diet: Diet
    target_weight_kg: float | None


class ProfileSaved(BaseModel):
    profile: ProfileOut
    targets: TargetsOut
    plan_ready: bool = Field(description="A workout plan exists for this profile")
    plan_rebuilt: bool = Field(description="The plan was (re)generated by this request")


ConfigOut.model_rebuild()  # resolves the "ProfileRules" forward reference


# ---------- Stage 3: exercise library ----------

class ExerciseItem(BaseModel):
    id: str
    name: str
    muscle_group: str = Field(description="Primary muscle")
    secondary_muscles: list[str]
    equipment: str
    difficulty: str
    movement_type: str
    home_friendly: bool
    image: str | None = Field(description="Thumbnail URL; null = no image yet")
    fits: bool | None = Field(description="Fits the user's equipment, level and injuries; null = no profile yet")


class ExerciseList(BaseModel):
    items: list[ExerciseItem] = Field(description="A-Z by name")
    total: int = Field(description="Exercises in the library (before filters)")
    muscles: list[str] = Field(description="Muscle groups, in curated order (for the chips)")
    equipment: list[str]
    difficulties: list[str]


class ExerciseMedia(BaseModel):
    kind: Literal["animation", "photo"] | None
    start: str | None
    peak: str | None
    still: str | None


class ExerciseDetail(ExerciseItem):
    media: ExerciseMedia
    form_tips: str | None
    reasons: list[Literal["equipment", "level", "injury"]] = Field(
        description="Why it isn't in your plans (empty = fits)")
    substitutes: list[ExerciseItem]


class MediaReport(BaseModel):
    both: list[str] = Field(description="Start and peak images: animated")
    one: list[str] = Field(description="One image: shown as a still")
    none: list[str]


# ---------- Stage 4: programs ----------

TrainingGoal = Literal["strength", "hypertrophy", "endurance"]


class PlanItemOut(BaseModel):
    id: int
    exercise: ExerciseItem
    sets: int
    rep_min: int
    rep_max: int
    timed: bool = Field(description="Reps are seconds")
    rest_seconds: int


class PlanDayOut(BaseModel):
    id: int
    program_id: int
    index: int
    name_key: str = Field(description='Text key ("upper", "custom"...); translate as day_<key>')
    suffix: str
    name: str | None = Field(description="A name the user typed (overrides name_key)")
    exercises: list[PlanItemOut]
    sets: int
    minutes: int = Field(description="Estimated duration")


class ProgramSummary(BaseModel):
    id: int
    name: str | None = Field(description="null = named after the split")
    split: str
    kind: Literal["template", "custom"]
    template_days: int | None
    goal: TrainingGoal
    weeks: int
    workouts_per_week: int
    is_current: bool
    edited: bool
    started_on: date | None
    ends_on: date | None
    week: int | None = Field(description="Current week (1-based), current program only")
    completed: int
    total: int = Field(description="weeks x workouts per week")
    next_day_index: int | None
    day_names: list[PlanDayOut] = Field(description="Days without exercises (for cards)")


class ProgramDetail(ProgramSummary):
    days: list[PlanDayOut]


class TemplateOut(BaseModel):
    days: int
    split: str
    recommended: bool = Field(description="Matches the training days in the profile")
    day_keys: list[str]


class ProgramsOut(BaseModel):
    current: ProgramSummary | None
    created: list[ProgramSummary] = Field(description="Saved programs that aren't current")
    available: list[TemplateOut] = Field(description="Built-in programs")


class ProgramCreate(BaseModel):
    name: str | None = Field(default=None, max_length=200)
    weeks: int = 8
    workouts_per_week: int = Field(default=3, description="Custom programs: number of empty days")
    goal: TrainingGoal = "hypertrophy"
    template_days: int | None = Field(default=None, description="Build from a built-in program")
    activate: bool = False


class ProgramPatch(BaseModel):
    name: str | None = Field(default=None, max_length=200, description="null = use the split name")
    weeks: int | None = None
    goal: TrainingGoal | None = None


class DayCreate(BaseModel):
    name: str | None = Field(default=None, max_length=200)


class DayPatch(BaseModel):
    name: str | None = Field(default=None, max_length=200)
    position: int | None = None


class ItemCreate(BaseModel):
    exercise_id: str = Field(max_length=80)


class ItemPatch(BaseModel):
    sets: int | None = None
    rep_min: int | None = None
    rep_max: int | None = None
    rest_seconds: int | None = None
    position: int | None = None


class SubstituteIn(BaseModel):
    exercise_id: str | None = Field(default=None, max_length=80, description="null = pick the best one")


class CalendarDayOut(BaseModel):
    date: date
    status: Literal["done", "missed", "planned", "rest"]


class CalendarOut(BaseModel):
    month: str
    days: list[CalendarDayOut]
    schedule: list[int] = Field(description="Scheduled weekdays, 0 = Monday")
    done: int
    planned: int = Field(description="Scheduled days this month")


class MuscleSets(BaseModel):
    muscle: str
    sets: float


class WeekMuscle(MuscleSets):
    level: Literal["low", "ok", "high"]


class EnergyWarning(BaseModel):
    key: Literal["session_long", "session_many_sets", "muscle_session_high", "weekly_high"]
    muscle: str | None = None
    value: float


class EnergyDay(BaseModel):
    sets: int
    minutes: int
    muscles: list[MuscleSets]


class EnergyOut(BaseModel):
    day: EnergyDay
    week: list[WeekMuscle]
    warnings: list[EnergyWarning]
